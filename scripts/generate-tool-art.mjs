#!/usr/bin/env node
/**
 * Wires each tool's own ink drawing to its page (DNA-SPEC §9).
 *
 * - Writes `src/lib/ink/drawings/tools/index.ts`: TOOL_ART, every drawing file
 *   in that folder keyed by tool id. It imports "server-only", so a client file
 *   that pulled in the whole map would fail the build.
 * - Writes `src/app/(tools)/<path>/layout.tsx` for every registry tool that
 *   has a drawing: a server layout that hands the page its drawing through
 *   <ToolArt>, so it reaches the browser as data, never as JS, and sets the
 *   tool's link-preview image (lib/seo/tool-share.ts).
 *
 * Idempotent: run it after adding or removing a drawing. `--check` writes
 * nothing and exits 1 if anything is out of date (test/ink/tool-art.test.ts
 * runs the same comparison).
 *
 *   node scripts/generate-tool-art.mjs [--check]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TOOLS_TS = path.join(ROOT, "src/lib/constants/tools.ts");
const ART_DIR = path.join(ROOT, "src/lib/ink/drawings/tools");
const APP_TOOLS = path.join(ROOT, "src/app/(tools)");
const MARK = "// Generated by scripts/generate-tool-art.mjs";

/** Every registry tool's id and path, in registry order. */
export function registryTools(source = readFileSync(TOOLS_TS, "utf8")) {
  const out = [];
  const re = /\{\s*\n\s*id:\s*"([^"]+)",[\s\S]*?\n\s*path:\s*"([^"]+)"/g;
  for (const m of source.matchAll(re)) out.push({ id: m[1], path: m[2] });
  return out;
}

/** `planning-poker` → `planningPoker`. */
const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function drawingIds() {
  if (!existsSync(ART_DIR)) return [];
  return readdirSync(ART_DIR)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
}

export function indexSource(ids) {
  const imports = ids.map((id) => `import ${camel(id)} from "./${id}";`).join("\n");
  const entries = ids.map((id) => `  ${JSON.stringify(id)}: ${camel(id)},`).join("\n");
  return `${MARK}; don't edit by hand.
import "server-only";
${imports}
import type { InkDrawing } from "../../types";

/**
 * Each tool's own spot drawing, keyed by tool id. Server only: a tool's route
 * layout passes its one drawing to the page (components/ink/tool-art.tsx).
 */
export const TOOL_ART: Record<string, InkDrawing> = {
${entries}
};
`;
}

export function layoutSource(id) {
  return `${MARK}; don't edit by hand.
import type { ReactNode } from "react";
import { ToolArt } from "@/components/ink/tool-art";
import { toolShareMetadata } from "@/lib/seo/tool-share";

// The tool's own link preview (app/og/tools/[id]) for every page under it.
export const metadata = toolShareMetadata(${JSON.stringify(id)});

export default function ToolLayout({ children }: { children: ReactNode }) {
  return <ToolArt id=${JSON.stringify(id)}>{children}</ToolArt>;
}
`;
}

/** Formatted as the repo's prettier would leave it, so lint-staged changes nothing. */
async function format(file, content) {
  const prettier = await import("prettier");
  const options = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(content, { ...options, filepath: file });
}

/** Every file this script owns, with the content it should have. */
export async function plannedFiles() {
  const ids = drawingIds();
  const have = new Set(ids);
  const files = [{ file: path.join(ART_DIR, "index.ts"), content: indexSource(ids) }];
  for (const tool of registryTools()) {
    if (!have.has(tool.id)) continue;
    files.push({
      file: path.join(APP_TOOLS, ...tool.path.split("/").filter(Boolean), "layout.tsx"),
      content: layoutSource(tool.id),
    });
  }
  return Promise.all(files.map(async (f) => ({ ...f, content: await format(f.file, f.content) })));
}

async function main() {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const { file, content } of await plannedFiles()) {
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === content) continue;
    if (current !== null && !current.startsWith(MARK)) {
      console.error(`refusing to overwrite a hand-written file: ${path.relative(ROOT, file)}`);
      process.exit(2);
    }
    stale.push(path.relative(ROOT, file));
    if (!check) writeFileSync(file, content);
  }
  if (check && stale.length) {
    console.error(`out of date (run node scripts/generate-tool-art.mjs):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(check ? "tool art up to date" : `wrote ${stale.length} file(s)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
