/**
 * What of the comic's canon may reach Meet the Cast. A fixed list of fields, not
 * a blocklist, so a new private field in a later canon stays out by default. The
 * canon also holds research ids, story engines, growth arcs and model-sheet
 * details: none of those is copied, and test/vip/cast-whitelist.test.ts checks it.
 *
 * Plain JS so both the generator (generate-cast.mjs) and the tests can run it.
 */

/** Copied from each entry in `cast`. Nothing else ever is. */
export const CAST_FIELDS = Object.freeze([
  "id",
  "name",
  "human_want",
  "strength",
  "overused_strength",
]);

/** Copied from each of an entry's relationship_hooks. */
export const HOOK_FIELDS = Object.freeze(["with", "collision", "advance"]);

function text(value, field, id) {
  if (typeof value !== "string") throw new Error(`canon: ${id} has no text for ${field}`);
  return value;
}

/** The cards from a parsed canon file, in canon order, whitelisted field by field. */
export function pickCast(canon) {
  if (!Array.isArray(canon?.cast)) throw new Error("canon: no cast list");
  return canon.cast.map((entry) => {
    const card = {};
    for (const field of CAST_FIELDS) card[field] = text(entry[field], field, entry.id);
    card.relationship_hooks = (entry.relationship_hooks ?? []).map((hook) => {
      const kept = {};
      for (const field of HOOK_FIELDS) kept[field] = text(hook[field] ?? "", field, entry.id);
      return kept;
    });
    return card;
  });
}

/** The committed server-only module, as text. */
export function renderCastModule(cards) {
  return `/**
 * The 30 colleagues of Agile at Work, for Meet the Cast and Which Colleague Are You?
 *
 * GENERATED by scripts/generate-cast.mjs from Agile_At_Work_Expanded_Canon.json.
 * Don't edit it by hand: the words belong to the bible. Only the fields listed in
 * scripts/cast-whitelist.mjs are copied, and this module is server-only, so the
 * text reaches a browser only as props on a page that has checked VIP access.
 */

import "server-only";
import type { CastCard } from "./cast";

export const CAST: readonly CastCard[] = ${JSON.stringify(cards, null, 2)};
`;
}
