/**
 * Writes the ChatGPT brief for Amr's context sheets from their spec.
 *
 *     node --no-warnings scripts/build-mascot-context-brief.mjs [--tools] [<page folder>]
 *
 * Without --tools: the context sheets S11–S64 (weather, time, holidays, toolkit
 * moments, play). Always rewrites docs/mascot/AMR-CONTEXT-BRIEF.md, and
 * AMR-CONTEXT-CHATGPT.md: everything ChatGPT needs in one file.
 *
 * With --tools: the tool sheets (the tools-* groups, S65 on), one per website
 * tool. Rewrites docs/mascot/AMR-TOOLS-BRIEF.md and AMR-TOOLS-CHATGPT.md. Their
 * prompts add the spec's tool rules (the haircut and rendering lessons of hair
 * rounds 2 and 3) and use the references ChatGPT gets in each batch's zip.
 *
 * With a folder, also writes a prompt page there (index.html, plus the reference
 * images under reference/): one card per sheet with a button that copies the
 * whole prompt, ready to paste into ChatGPT, and for the tool sheets a kickoff
 * message per batch.
 *
 * The spec is docs/mascot/context-sheets.json; the master block is the one in
 * docs/mascot/AMR-ART-BRIEF.md, so every sheet is drawn to the same rules.
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = path.join(ROOT, "docs", "mascot");
const spec = JSON.parse(readFileSync(path.join(DOCS, "context-sheets.json"), "utf8"));
const brief = readFileSync(path.join(DOCS, "AMR-ART-BRIEF.md"), "utf8");

/** The master block: the first text fence after "## 2. Master block". */
function masterBlock() {
  const from = brief.indexOf("## 2. Master block");
  const m = brief.slice(from).match(/```text\n([\s\S]*?)\n```/);
  if (from < 0 || !m) throw new Error("No master block in AMR-ART-BRIEF.md");
  return m[1].trim();
}

const MASTER = masterBlock();
const ADDENDUM = spec.addendum.trim();

// Which sheets this run is for: the context sheets, or (--tools) the tool sheets.
const TOOLS = process.argv.includes("--tools");
const isTool = (s) => s.group.startsWith("tools-");
const SHEETS = spec.sheets.filter((s) => isTool(s) === TOOLS);
const GROUPS = spec.groups.filter((g) => g.id.startsWith("tools-") === TOOLS);
const RANGE = `${SHEETS[0].sheet}–${SHEETS[SHEETS.length - 1].sheet}`;
const TOOL_RULES = TOOLS ? spec.tools_addendum.trim() : "";

/** 54 → "Fifty-four". */
function words(n) {
  const ones =
    "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen".split(
      " "
    );
  const tens = [
    "",
    "",
    "twenty",
    "thirty",
    "forty",
    "fifty",
    "sixty",
    "seventy",
    "eighty",
    "ninety",
  ];
  const w = n < 20 ? ones[n] : tens[Math.floor(n / 10)] + (n % 10 ? `-${ones[n % 10]}` : "");
  return w[0].toUpperCase() + w.slice(1);
}

/** The sheet's own block, as the image model reads it. */
function sheetBlock(s) {
  const lines = [
    `SHEET ${s.sheet} — ${s.title.toUpperCase()}. ${s.props}`,
    "1. The standard stance, exactly as in ref-1.",
    ...s.slots.map((slot, i) => `${i + 2}. ${slot.pose}`),
  ];
  return lines.join("\n");
}

const fileName = (s) => `${s.sheet}-${s.pack}.png`;
const prompt = (s) => [MASTER, ADDENDUM, TOOL_RULES, sheetBlock(s)].filter(Boolean).join("\n\n");
