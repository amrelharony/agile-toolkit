/**
 * Writes the ChatGPT brief for Amr's context sheets S11–S64 from their spec.
 *
 *     node --no-warnings scripts/build-mascot-context-brief.mjs [<page folder>]
 *
 * Always rewrites docs/mascot/AMR-CONTEXT-BRIEF.md, and AMR-CONTEXT-CHATGPT.md:
 * everything ChatGPT needs in one file. With a folder, also writes a
 * prompt page there (index.html, plus the reference images under reference/):
 * one card per sheet with a button that copies the whole prompt, the master
 * block, the context rules and the sheet, ready to paste into ChatGPT.
 *
 * The spec is docs/mascot/context-sheets.json; the master block is the one in
 * docs/mascot/AMR-ART-BRIEF.md, so every sheet is drawn to the same rules.
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = path.join(ROOT, "docs", "mascot");
const spec = JSON.parse(readFileSync(path.join(DOCS, "context-sheets.json"), "utf8"));
const brief = readFileSync(path.join(DOCS, "AMR-ART-BRIEF.md"), "utf8");

/** The master block: the first text fence after "## 2. Master block". */
function masterBlock() {
  const from = brief.indexOf("## 2. Master block");
  const m = brief.slice(from).match(/```text\n([\s\S]*?)\n```/);
  if (from < 0 || !m) throw new Error("No master block in AMR-ART-BRIEF.md");
  return m[1].trim();
}

const MASTER = masterBlock();
const ADDENDUM = spec.addendum.trim();

/** The sheet's own block, as the image model reads it. */
function sheetBlock(s) {
  const lines = [
    `SHEET ${s.sheet} — ${s.title.toUpperCase()}. ${s.props}`,
    "1. The standard stance, exactly as in ref-1.",
    ...s.slots.map((slot, i) => `${i + 2}. ${slot.pose}`),
  ];
  return lines.join("\n");
}

const fileName = (s) => `${s.sheet}-${s.pack}.png`;
const prompt = (s) => `${MASTER}\n\n${ADDENDUM}\n\n${sheetBlock(s)}`;
const bySheet = new Map(spec.sheets.map((s) => [s.sheet, s]));

