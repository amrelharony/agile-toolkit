/**
 * Everything ChatGPT needs in one file, to attach once (to a Project, or to the
 * first message of a chat) with the reference images: how to answer, the master
 * block, the context rules, and every sheet's block in sheet order. No frame
 * ids or tables, which an image model may draw as text.
 */
function chatgpt() {
  const out = [];
  out.push(
    "# Amr: context sheets S11–S64",
    "",
    "<!-- Generated by scripts/build-mascot-context-brief.mjs from context-sheets.json. Edit the JSON, then run the script. -->",
    "",
    "## For the person",
    "",
    "1. Put this file and five images in a ChatGPT Project's files, or attach them all to the first message of a chat: `ref-1-stance.png`, `ref-hair.png`, `ref-2-detail.png`, `ref-3-range.png` (from `docs/mascot/reference/`) and the approved `S01-faces.png`.",
    "2. Then send one sheet code at a time, for example `S11`.",
    "3. Check the image, and save it under the file name its section gives.",
    "4. Start a new chat every eight sheets or so, with the file and images attached again, so he doesn't drift.",
    "",
    "Suggested order:",
    ""
  );
  for (const r of spec.rounds) out.push(`- **${r.title}:** ${r.sheets.join(", ")}`);
  out.push(
    "",
    "## For ChatGPT: how to answer",
    "",
    "This file is a brief for sprite sheets of Amr, a small animated character. The person will name one sheet at a time by its code, such as `S11`. For each one:",
    "",
    "1. Make exactly one image: **1536 × 1024 pixels, landscape, fully transparent background, PNG, high quality.**",
    "2. Follow the **Master block**, then the **Context rules**, then the named sheet's block below. Draw only that sheet's poses; where it says a prop is the same as another sheet's, take that prop's description from the other sheet.",
    "3. The attached images are the references the master block names: `ref-1-stance.png` is ref-1, `ref-hair.png` is ref-hair, `ref-2-detail.png` is ref-2, `ref-3-range.png` is ref-3, and `S01-faces.png` is ref-4, the approved sheet to match.",
    "4. Draw nothing from this file as text in the image: no sheet codes, titles, file names, slot numbers or labels.",
    "5. Ask nothing back and add no commentary: just make the image.",
    "",
    "If the person asks to fix a slot, edit the last image: keep every other slot exactly as it is and redraw only that slot. If the person says the background isn't transparent, make it again with one flat, solid magenta colour (#FF00FF) everywhere outside the character, with no gradient, no shadow and no texture (never green, never white).",
    "",
    "## Master block",
    "",
    "```text",
    MASTER,
    "```",
    "",
    "## Context rules",
    "",
    "```text",
    ADDENDUM,
    "```",
    "",
    "## Sheets",
    ""
  );
  for (const s of spec.sheets) {
    out.push(
      `### ${s.sheet}: ${s.title}`,
      "",
      `Save as \`${fileName(s)}\`.`,
      "",
      "```text",
      sheetBlock(s),
      "```",
      ""
    );
  }
  return out.join("\n");
}

