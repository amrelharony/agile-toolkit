// @vitest-environment node
/**
 * rigs.ts picks the rigs a server page passes to its figures: by cast name or
 * id, in the order asked, without the colleagues not shipped yet, and never
 * past the page's count or byte cap.
 */

import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it, vi } from "vitest";

import type { RigManifest } from "@/lib/cast/rig-types";
import { rigFor, rigsFor } from "@/lib/cast/rigs";
import { ARMLESS_PUPPET, TEST_PUPPET } from "./fixtures/rig-fixture";

vi.mock("@/lib/cast/rigs.generated", async () => {
  const { ARMLESS_PUPPET: armless, TEST_PUPPET: puppet } = await import("./fixtures/rig-fixture");
  const third: RigManifest = {
    ...puppet,
    id: "AAW-92",
    name: "Third Puppet",
    atlas: { ...puppet.atlas, bytes2: 10_000 },
  };
  return { RIGS: { "AAW-90": puppet, "AAW-91": armless, "AAW-92": third } };
});

const read = (file: string) => readFileSync(path.join(process.cwd(), file), "utf8");

describe("rigFor", () => {
  it("finds a rig by cast name or by id", () => {
    expect(rigFor("Test Puppet")).toBe(TEST_PUPPET);
    expect(rigFor("AAW-91")).toBe(ARMLESS_PUPPET);
  });

  it("has nothing for a colleague not shipped yet, or a name that isn't one", () => {
    expect(rigFor("Amr")).toBeNull();
    expect(rigFor("")).toBeNull();
    expect(rigFor("toString")).toBeNull();
  });
});

describe("rigsFor", () => {
  const roomy = { max: 10, bytes: 1_000_000 };

  it("keeps the order asked, without unknown, unshipped or repeated names", () => {
    const got = rigsFor(["Third Puppet", "Amr", "Nobody", "AAW-90", "Test Puppet"], roomy);
    expect(got.map((r) => r.id)).toEqual(["AAW-92", "AAW-90"]);
  });

  it("stops at the count", () => {
    const got = rigsFor(["AAW-90", "AAW-91", "AAW-92"], { ...roomy, max: 2 });
    expect(got.map((r) => r.id)).toEqual(["AAW-90", "AAW-91"]);
  });

  it("stops before the rig that would pass the byte cap, counting the 2x atlases", () => {
    // 30 000 + 50 000 = 80 000 fits; the third would make 90 000.
    const names = ["AAW-90", "AAW-91", "AAW-92"];
    expect(rigsFor(names, { max: 3, bytes: 80_000 }).map((r) => r.id)).toEqual([
      "AAW-90",
      "AAW-91",
    ]);
    // It stops rather than skip: a smaller rig later never takes an earlier one's place.
    expect(rigsFor(names, { max: 3, bytes: 70_000 }).map((r) => r.id)).toEqual(["AAW-90"]);
    expect(rigsFor(names, { max: 3, bytes: 29_999 })).toEqual([]);
    expect(rigsFor(names, { max: 3, bytes: 90_000 })).toHaveLength(3);
  });
});

describe("the rig modules", () => {
  it("keep the lookup server-only and the generated data plain", () => {
    expect(read("src/lib/cast/rigs.ts")).toMatch(/^import "server-only";$/m);
    const generated = read("src/lib/cast/rigs.generated.ts");
    expect(generated).toMatch(/GENERATED by `python -I scripts\/build-cast-rigs\.py build`/);
    expect(generated).not.toMatch(/import\s+["']server-only["']/);
    expect(generated).toMatch(/^import type \{ RigManifest \} from "\.\/rig-types";$/m);
    expect(generated).toMatch(/^export const RIGS: Readonly<Record<string, RigManifest>> = /m);
  });

  it("type the ID card's cord as cord", () => {
    const types = read("src/lib/cast/rig-types.ts");
    expect(types).toMatch(/\| "cord"/);
    expect(types).not.toMatch(/lanyard/i);
    // Import-free, for Node's type stripping.
    expect(types).not.toMatch(/^import /m);
  });
});
