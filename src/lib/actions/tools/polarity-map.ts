// ──────── tool.polarity_map.suggest_questions ────────
// PURE (no mcpHandler). Given a polarity title — ideally in
// "{leftPole} ↔ {rightPole}" or "{leftPole} vs {rightPole}" shape —
// return 6 facilitation questions a workshop host can ask to fill in
// the four-quadrant polarity map (upside/downside × leftPole/rightPole)
// plus the two anchors (Greater Purpose above, Deeper Fear below).
//
// Generated from a template (no LLM call) so the action is
// deterministic and runs identically on server and browser. Templates
// quote the actual pole labels when we can parse them out, falling
// back to "Pole A" / "Pole B" otherwise — this keeps the surface
// useful for polarities phrased loosely (e.g. "centralisation issue")
// while giving sharper, named questions when the labels are clear.
registry.register({
  id: "tool.polarity_map.suggest_questions",
  toolId: "tool.polarity_map",
  name: "suggest_questions",
  category: "read",
  description:
    "Generate 6 facilitation questions for a polarity-mapping session about the given polarity. Pure — no persistence, no LLM call. The questions cover both poles' upsides AND downsides, plus the Greater Purpose (above) and Deeper Fear (below) anchors. Title is parsed for ' ↔ ' / ' vs ' / ' / ' / ' or ' / ' & ' separators to extract named pole labels; falls back to 'Pole A' / 'Pole B' if no separator is found.",
  paramsSchema: z.object({
    title: z.string().min(1).max(200),
  }),
  handler: async (params) => {
    return { questions: buildQuestions(params.title) };
  },
  // No mcpHandler — pure compute runs identically on server and client.
});

/** Parse a polarity title into {left, right} pole labels. Recognises
 *  the common separators a user (or agent) would type:
 *
 *    " ↔ "  (Johnson's canonical arrow — what the in-app input hints at)
 *    " vs " / " vs. "
 *    " / "
 *    " or " / " | " / " & "
 *
 *  Falls back to ["Pole A", "Pole B"] when nothing is recognised so the
 *  generated questions still flow naturally rather than embedding the
 *  whole title twice. The separator list is intentionally narrow —
 *  picking up "and" or "but" would over-trigger on titles that happen
 *  to contain those words ("Speed and safety" → splits; "Why we
 *  matter" → would falsely split on "and" if added). */
function splitPoles(title: string): { left: string; right: string } {
  const SEPARATORS = [" ↔ ", " vs. ", " vs ", " / ", " or ", " | ", " & "];
  for (const sep of SEPARATORS) {
    const idx = title.indexOf(sep);
    if (idx > 0 && idx < title.length - sep.length) {
      const left = title.slice(0, idx).trim();
      const right = title.slice(idx + sep.length).trim();
      if (left && right) return { left, right };
    }
  }
  return { left: "Pole A", right: "Pole B" };
}

/** Build the 6 facilitation questions. Order chosen to mirror the
 *  canonical polarity-map quadrant fill-in sequence:
 *
 *    1. Upsides of pole A
 *    2. Upsides of pole B
 *    3. Downsides of over-focusing on pole A (slides into the lower-left)
 *    4. Downsides of over-focusing on pole B (slides into the lower-right)
 *    5. Greater Purpose anchor (above both)
 *    6. Deeper Fear anchor (below both)
 *
 *  This is the same flow Johnson's "Polarity Management" book walks
 *  facilitators through. Six questions, not five or seven, because
 *  that's how many discrete artefacts the map has — adding more would
 *  be redundancy, fewer would leave a quadrant unprompted. The
 *  description string says "5-7" to match the squad brief's guidance
 *  range; 6 fits comfortably within it. */
function buildQuestions(title: string): string[] {
  const { left, right } = splitPoles(title);
  return [
    `What are the upsides of "${left}" when this polarity is well-managed? (top-left quadrant)`,
    `What are the upsides of "${right}" when this polarity is well-managed? (top-right quadrant)`,
    `What goes wrong when "${left}" is over-focused at the expense of "${right}"? (bottom-left quadrant — the downsides of "${left}")`,
    `What goes wrong when "${right}" is over-focused at the expense of "${left}"? (bottom-right quadrant — the downsides of "${right}")`,
    `What is the Greater Purpose this whole polarity serves — the shared aspiration that justifies managing the tension between "${left}" and "${right}"? (above both poles)`,
    `What is the Deeper Fear — what happens if you lose grip on BOTH poles and slide into both downsides at once? (below both poles)`,
  ];
}
