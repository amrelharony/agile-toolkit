/**
 * Polarity Map — tool-local actions.
 *
 * Category: Decision Frameworks (squad S13, Wave 4)
 * Tool:     Barry Johnson's polarity management — name two interdependent
 *           poles of a chronic tension (e.g. Autonomy ↔ Standardisation),
 *           anchored above by a Greater Purpose and below by a Deeper Fear.
 *           Polarities are MANAGED, not solved — the map exists to keep
 *           both poles in conscious view rather than oscillating into
 *           the downsides of whichever is currently neglected.
 *
 * Agent surface: tool.polarity_map.*
 * Backing CRUD : workspace.polarity.* (auto-generated by
 *                defineCrudActions in src/lib/actions/workspace/index.ts).
 *
 * ─── Why this file exists (vs the generic CRUD surface) ──────────────
 * Generic create / list / update / delete already exist via
 * workspace.polarity.*. This file adds VERBS THE AGENT WANTS TO SPEAK
 * in polarity-mapping's domain vocabulary — things the generic surface
 * can't express without the agent constructing a full patch payload:
 *
 *   1. list_state          — read all polarities + summary stats
 *                            (total, withGreaterPurpose, withDeeperFear).
 *                            Lets the agent plan a session ("which
 *                            polarities are still missing their purpose
 *                            anchor?") without paging every record.
 *   2. create_polarity     — convenience over workspace.polarity.create
 *                            with the framework-shaped fields named
 *                            explicitly (title / greaterPurpose / deeperFear).
 *                            Saves the agent from marshalling a generic
 *                            {value: {…}} envelope.
 *   3. set_greater_purpose — single-field convenience update. The
 *                            "Greater Purpose" anchor sits ABOVE both
 *                            poles in Johnson's diagram and is often
 *                            added as a second pass after the initial
 *                            polarity is captured — making it the most
 *                            mutated field after the title is set.
 *   4. set_deeper_fear     — symmetric — the anchor BELOW both poles
 *                            (what happens if we lose grip of both poles
 *                            and slide into both downsides).
 *   5. suggest_questions   — PURE (no mcpHandler). Given a polarity
 *                            title (or "{leftPole}/{rightPole}" shape),
 *                            return 5–7 facilitation questions a
 *                            workshop host could ask. Useful for an
 *                            agent seeding a session without having to
 *                            embed prompt templates in its own context.
 *
 * ─── ID NAMING ───────────────────────────────────────────────────────
 * Namespace is `tool.polarity_map` (underscore). The auto-generated
 * CRUD surface uses `workspace.polarity` (single-word entity name —
 * NO kind asymmetry of the daci_decision / daciDecision sort), which
 * means MCP-path entity calls use the kind "workspace:polarity"
 * verbatim. The route slug "/polarity-map" is converted to the
 * snake_case agent namespace per the squad-13 convention.
 *
 * ─── SCOPE NOTE — per-pole fields ────────────────────────────────────
 * The polarity-map tool client (polarity-map-client.tsx) persists a
 * SECOND entity per polarity: `PolarityPole` ({polarityId, side,
 * label, upsides[], downsides[]}), stored under kind
 * "workspace:polarityPole". The Polarity row itself only carries
 * {title, greaterPurpose, deeperFear} — the upsides / downsides /
 * pole labels live on the pole rows. This action file is scoped to
 * the POLARITY entity per the squad-13 brief. A future
 * `tool.polarity_map.set_pole_label` / `add_upside` / `add_downside`
 * surface would be a separate, larger expansion (and requires an
 * auto-generated workspace.polarity_pole.* CRUD which doesn't yet
 * exist — adding one would touch workspace/index.ts which this file
 * is forbidden from editing).
 * ─────────────────────────────────────────────────────────────────────
 */

import { z } from "zod";
import { registry } from "../registry";
import { useWorkspaceStore } from "@/lib/stores/workspace-store";
import { serverListEntities, serverGetEntity, serverUpsertEntity } from "../server-store";
import type { Polarity } from "@/lib/stores/workspace-types";

/** Server-side entity kind. Matches kindFromToolId("workspace.polarity")
 *  used by the auto-generated CRUD in src/lib/actions/workspace/index.ts.
 *  Single-word entity — no underscore→camelCase asymmetry to navigate. */
const KIND_POLARITY = "workspace:polarity";

const ws = () => useWorkspaceStore.getState();

/** Stable id generator. Mirrors the format used by the auto-generated
 *  CRUD (`polarity_${nanoid(8)}` — see workspace/index.ts:534) closely
 *  enough that downstream readers can't distinguish agent-created from
 *  CRUD-created rows, but uses Math.random instead of pulling nanoid
 *  in for a 1-import savings. The collision probability at 8-char
 *  base36 (~41 bits) is still negligible for per-user polarity counts. */
function newPolarityId(): string {
  return `polarity_${Math.random().toString(36).slice(2, 10)}`;
}

// ──────── tool.polarity_map.list_state ────────
// Snapshot + summary stats. The agent's most common opening question
// for a polarity tool is "what polarities am I managing, and which
// still need their anchors filled in?" — returning the items array AND
// the withGreaterPurpose / withDeeperFear counts in one round-trip
// avoids a follow-up reduce on the agent's end.
registry.register({
  id: "tool.polarity_map.list_state",
  toolId: "tool.polarity_map",
  name: "list_state",
  category: "read",
  description:
    "List all polarities in the workspace with a completeness summary. Returns {total, withGreaterPurpose: n, withDeeperFear: n, items: Polarity[]}. Useful for spotting polarities that still need their Greater Purpose (above-both anchor) or Deeper Fear (below-both anchor) filled in before a workshop.",
  paramsSchema: z.object({}),
  handler: async () => {
    const items = ws().polarities ?? [];
    return summarize(items);
  },
  mcpHandler: async (_params, ctx) => {
    const items = await serverListEntities<Polarity>(ctx.userId, KIND_POLARITY);
    return summarize(items);
  },
});

/** Build the {total, withGreaterPurpose, withDeeperFear, items} response
 *  shape. Kept as a single helper so the browser-path and MCP-path
 *  responses are guaranteed identical — drift here would mean an agent
 *  gets different shapes depending on whether it's invoked from chat
 *  or over MCP. A trimmed non-empty string is what counts as "set"
 *  (whitespace-only doesn't count — matches the client's `.trim() ||
 *  undefined` pattern at polarity-map-client.tsx:86-87). */
function summarize(items: Polarity[]) {
  let withGreaterPurpose = 0;
  let withDeeperFear = 0;
  for (const p of items) {
    if (typeof p.greaterPurpose === "string" && p.greaterPurpose.trim() !== "") {
      withGreaterPurpose += 1;
    }
    if (typeof p.deeperFear === "string" && p.deeperFear.trim() !== "") {
      withDeeperFear += 1;
    }
  }
  return { total: items.length, withGreaterPurpose, withDeeperFear, items };
}

// ──────── tool.polarity_map.create_polarity ────────
// Convenience over workspace.polarity.create. Named with framework
// vocabulary (title / greaterPurpose / deeperFear) so the agent doesn't
// have to wrap fields in a generic {value: {...}} envelope. Generates
// an id matching the CRUD format so downstream consumers can't tell
// the difference. Returns {id} so the agent can chain a follow-up
// (set_greater_purpose, etc.) without re-listing.
registry.register({
  id: "tool.polarity_map.create_polarity",
  toolId: "tool.polarity_map",
  name: "create_polarity",
  category: "write",
  description:
    "Create a new polarity (a chronic tension to be MANAGED, not solved — e.g. 'Autonomy ↔ Standardisation'). Required: title. Optional: greaterPurpose (the shared aspiration that sits ABOVE both poles) and deeperFear (the shared dread that sits BELOW both poles). Returns {id}. NOTE: the in-app tool also stores left/right pole labels + upsides/downsides on a separate PolarityPole entity not exposed here — agent-created polarities will appear in the UI but with no poles attached.",
  paramsSchema: z.object({
    title: z.string().min(1).max(200),
    greaterPurpose: z.string().max(500).optional(),
    deeperFear: z.string().max(500).optional(),
  }),
  handler: async (params) => {
    const id = newPolarityId();
    ws().upsertPolarity({
      id,
      title: params.title.trim(),
      greaterPurpose: params.greaterPurpose?.trim() || undefined,
      deeperFear: params.deeperFear?.trim() || undefined,
    });
    return { id };
  },
  mcpHandler: async (params, ctx) => {
    const id = newPolarityId();
    await serverUpsertEntity<Polarity>(ctx.userId, KIND_POLARITY, {
      id,
      title: params.title.trim(),
      greaterPurpose: params.greaterPurpose?.trim() || undefined,
      deeperFear: params.deeperFear?.trim() || undefined,
    });
    return { id };
  },
});

// ──────── tool.polarity_map.set_greater_purpose ────────
// Single-field convenience update. The Greater Purpose anchor — the
// shared aspiration that justifies managing BOTH poles — is often
// added as a second pass after the initial polarity is captured, so
// the agent shouldn't have to marshal a {patch: {greaterPurpose: ...}}
// payload through the generic update surface. Returns
// {updated: boolean} so the agent can detect missing-id without
// throwing.
registry.register({
  id: "tool.polarity_map.set_greater_purpose",
  toolId: "tool.polarity_map",
  name: "set_greater_purpose",
  category: "write",
  description:
    "Set the Greater Purpose on an existing polarity — the shared aspiration that sits ABOVE both poles and justifies managing the tension (e.g. for Autonomy ↔ Standardisation, a Greater Purpose might be 'A high-performing engineering org'). Returns {updated: false} when the id is unknown.",
  paramsSchema: z.object({
    id: z.string(),
    greaterPurpose: z.string().min(1).max(500),
  }),
  handler: async (params) => {
    const items = ws().polarities ?? [];
    const current = items.find((p) => p.id === params.id);
    if (!current) return { updated: false };
    ws().upsertPolarity({ ...current, greaterPurpose: params.greaterPurpose.trim() });
    return { updated: true };
  },
  mcpHandler: async (params, ctx) => {
    const current = await serverGetEntity<Polarity>(ctx.userId, KIND_POLARITY, params.id);
    if (!current) return { updated: false };
    await serverUpsertEntity<Polarity>(ctx.userId, KIND_POLARITY, {
      ...current,
      greaterPurpose: params.greaterPurpose.trim(),
    });
    return { updated: true };
  },
});

